    public String getSceneDescription(int sceneId, String playerName) {
        return String.format(scenes.getOrDefault(sceneId, "Сцена не найдена."), playerName);
    }

    public int processChoice(int currentSceneId, String choice) {
        Map<String, Integer> sceneChoices = choices.get(currentSceneId);
        if (sceneChoices != null && sceneChoices.containsKey(choice)) {
            return sceneChoices.get(choice);
        }
        return currentSceneId; // Если выбор не найден, остаемся на текущей сцене
    }
